# -*- coding: utf-8 -*-
"""Rebuild index.json + demo/screens-data.js from apps/*/*/meta.json."""
import json, os, glob, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APPS = {"grok-bot": {"name": "Grok Bot", "order": 0}, "codex": {"name": "Codex", "order": 1},
        "chatgpt-web": {"name": "ChatGPT Web", "order": 2}, "gemini-web": {"name": "Gemini", "order": 3},
        "cursor": {"name": "Cursor", "order": 4}, "antigravity": {"name": "Antigravity", "order": 5}, "qoder": {"name": "Qoder", "order": 9}}
LABELS = {
 "grok-bot/main": "主聊天", "grok-bot/details-info-tab": "对话详情 · 详情", "grok-bot/details-media-tab": "对话详情 · 资料库",
 "grok-bot/details-computer-tab": "对话详情 · 电脑", "grok-bot/sidebar-search": "搜索面板", "grok-bot/new-chat-empty": "新建聊天（空态）",
 "grok-bot/account-menu": "账户菜单", "grok-bot/settings": "设置 · 通用", "grok-bot/settings-computer": "设置 · 电脑",
 "grok-bot/settings-usage": "设置 · 用量与账单", "grok-bot/settings-updates": "设置 · 更新",
 "codex/main": "首页", "codex/chatgpt-mode-main": "ChatGPT 模式 · 首页", "codex/chat-thread": "对话态", "codex/mode-switcher": "模式切换", "codex/search": "搜索", "codex/activity": "活动视图",
 "codex/images": "图像", "codex/scheduled-tasks": "定时任务", "codex/library": "资料库", "codex/plugins": "插件",
 "codex/more-menu": "更多菜单", "codex/code-review": "代码审查（不可用）", "codex/profile-menu": "个人资料菜单", "codex/profile": "个人资料页",
}
CODEX_SETTINGS = ["general:常规","notifications:通知","import:导入","appearance:外观","account:账户","archived-chats:已归档聊天","ads:广告设置",
 "parental-controls:家长控制","trusted-contacts:受信任联系人","voice:语音","config:配置","personalization:个性化","mini-pet:Mini 与虚拟宠物",
 "shortcuts:键盘快捷键","usage-billing:使用情况和计费","data-controls:数据管理","plugins:插件","computer-use:电脑操控","app-snapshots:应用快照",
 "browser:浏览器","cloud-computer:云电脑","hooks:钩子","connections:连接","cloud-preferences:云端偏好设置","code-review:代码审查","git:Git",
 "environments:环境","worktrees:Worktrees","password:密码"]
for s in CODEX_SETTINGS:
    k, v = s.split(":", 1); LABELS["codex/settings-" + k] = "设置 · " + v
ORDER = list(LABELS.keys())

def group_of(eid):
    scr = eid.split("/", 1)[1]
    if scr.startswith("settings"): return "设置"
    if scr in ("account-menu", "profile-menu", "profile", "mode-switcher", "more-menu", "search", "sidebar-search"): return "菜单与弹层"
    return "主要页面"

entries = []
for meta_path in glob.glob(os.path.join(ROOT, "apps", "*", "*", "meta.json")):
    d = os.path.dirname(meta_path); screen = os.path.basename(d); slug = os.path.basename(os.path.dirname(d))
    if screen.startswith("_"): continue
    with open(meta_path, encoding="utf-8-sig") as f: m = json.load(f)
    eid = f"{slug}/{screen}"
    rel = f"apps/{slug}/{screen}"
    e = {"id": eid, "app": m.get("app") or APPS.get(slug, {}).get("name", slug), "slug": slug, "screen": screen,
         "label": LABELS.get(eid, screen), "group": group_of(eid), "tier": m.get("tier", "first"),
         "tags": m.get("style_tags") or [], "layout": m.get("layout", ""), "nav": m.get("nav", ""),
         "clicks": m.get("clicks") or (m.get("interaction") or {}).get("steps") or [], "notes": m.get("notes", ""),
         "privacy": m.get("privacy", ""), "captured_at": m.get("captured_at", ""),
         "full_px": m.get("full_px", ""), "ai_px": m.get("ai_px", ""),
         "shot_full": rel + "/shot.png", "shot_ai": rel + "/shot-ai.jpg", "meta": rel + "/meta.json",
         "bytes_full": os.path.getsize(os.path.join(d, "shot.png")), "bytes_ai": os.path.getsize(os.path.join(d, "shot-ai.jpg"))}
    e["clicks"] = [c if isinstance(c, str) else json.dumps(c, ensure_ascii=False) for c in e["clicks"]]
    entries.append(e)
GORD = {"主要页面": 0, "菜单与弹层": 1, "设置": 2}
entries.sort(key=lambda e: (APPS.get(e["slug"], {"order": 5})["order"], GORD.get(e["group"], 3), ORDER.index(e["id"]) if e["id"] in ORDER else 999, e["id"]))

idx_path = os.path.join(ROOT, "index.json")
idx = {}
if os.path.exists(idx_path):
    with open(idx_path, encoding="utf-8-sig") as f: idx = json.load(f)
idx["version"] = 3
idx["updated_at"] = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
idx.setdefault("automation", {})["proven_path"] = "Grok Bot: 打开账户菜单 -> MenuItem 设置 -> Window Grok Bot 设置; Codex: 打开个人资料菜单 -> 设置 Ctrl+, -> 设置导航"
idx["entries"] = entries
with open(idx_path, "w", encoding="utf-8") as f: json.dump(idx, f, ensure_ascii=False, indent=2)

demo = os.path.join(ROOT, "demo"); os.makedirs(demo, exist_ok=True)
data = {"generated_at": idx["updated_at"], "apps": [{"slug": k, **v} for k, v in APPS.items() if any(e["slug"] == k for e in entries)], "entries": entries}
with open(os.path.join(demo, "screens-data.js"), "w", encoding="utf-8") as f:
    f.write("// generated by scripts/build_demo.py — do not edit\nwindow.SCREENS = ")
    json.dump(data, f, ensure_ascii=False, indent=1); f.write(";\n")
print(f"entries={len(entries)}", {s: sum(1 for e in entries if e['slug']==s) for s in APPS})
